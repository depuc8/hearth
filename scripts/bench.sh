#!/usr/bin/env bash
# Benchmarks hearth with wrk and writes bench/results.md.
#
#   scripts/bench.sh                 # wrk -t4 -c64 -d30s against / and /style.css
#   DURATION=10s scripts/bench.sh    # shorter run
#
# Environment: PORT (18080), THREADS (hearth workers, default: core count),
# DURATION (30s), WRK_THREADS (4), WRK_CONNECTIONS (64), HEARTH_BIN.
#
# Numbers are only ever copied from wrk's output. If wrk is missing, the
# results file says so and keeps a placeholder table.
set -euo pipefail
cd "$(dirname "$0")/.."

PORT="${PORT:-18080}"
DURATION="${DURATION:-30s}"
WRK_THREADS="${WRK_THREADS:-4}"
WRK_CONNECTIONS="${WRK_CONNECTIONS:-64}"
HEARTH_BIN="${HEARTH_BIN:-build/release/src/hearth}"
OUT="bench/results.md"
TARGETS=("/" "/style.css")

cores() { nproc 2>/dev/null || sysctl -n hw.ncpu; }
THREADS="${THREADS:-$(cores)}"

cpu_model() {
  if [[ -r /proc/cpuinfo ]]; then
    grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ *//'
  else
    sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown
  fi
}

os_name() {
  if [[ -r /etc/os-release ]]; then
    # shellcheck source=/dev/null
    (. /etc/os-release && echo "${PRETTY_NAME}")
  else
    echo "$(sw_vers -productName 2>/dev/null) $(sw_vers -productVersion 2>/dev/null)"
  fi
}

machine_info() {
  cat <<EOF
| | |
| --- | --- |
| Date | $(date -u '+%Y-%m-%d %H:%M UTC') |
| CPU | $(cpu_model) |
| Cores (logical) | $(cores) |
| OS | $(os_name) |
| Kernel | $(uname -srm) |
| Compiler | $(${CXX:-c++} --version 2>/dev/null | head -1) |
| hearth | $("$HEARTH_BIN" --version 2>/dev/null || echo "not built") (\`--threads ${THREADS}\`) |
| Load generator | ${LOAD_GENERATOR} on the same machine |
EOF
}

write_header() {
  cat >"$OUT" <<EOF
# Benchmark results

Generated by \`scripts/bench.sh\`. Client and server share the machine, so
the numbers measure the whole loopback path and are best read relative to
each other, not as absolute capacity.

## Machine

$(machine_info)

EOF
}

mkdir -p bench
LOAD_GENERATOR="wrk \`-t${WRK_THREADS} -c${WRK_CONNECTIONS} -d${DURATION} --latency\`"

start_server() {
  if [[ ! -x "$HEARTH_BIN" ]]; then
    echo "building release binary..." >&2
    cmake --preset release >/dev/null
    cmake --build --preset release --target hearth >/dev/null
  fi
  "$HEARTH_BIN" --port "$PORT" --threads "$THREADS" --root public >/dev/null 2>&1 &
  SERVER_PID=$!
  trap 'kill -INT "$SERVER_PID" 2>/dev/null || true; wait "$SERVER_PID" 2>/dev/null || true' EXIT
  for _ in $(seq 1 50); do
    if curl -fs -o /dev/null "http://127.0.0.1:${PORT}/"; then
      return
    fi
    sleep 0.1
  done
}

# Supplementary run with ApacheBench when wrk is unavailable. Clearly labelled
# as such: it is not a substitute for the wrk table.
run_ab_supplement() {
  local seconds="${DURATION%s}" target raw
  start_server
  {
    echo
    echo "## Supplementary: ApacheBench"
    echo
    echo "wrk was unavailable, so as a stand-in these numbers come from"
    echo "\`ab -k -c ${WRK_CONNECTIONS} -t ${seconds}\` (keep-alive, ${WRK_CONNECTIONS} concurrent"
    echo "connections, ${seconds}s per target). ab drives all connections from a *single*"
    echo "thread, so it usually saturates before the server does: read these as"
    echo "a lower bound, and don't compare them directly with wrk results."
    echo
    echo "| Target | Requests/sec | Transfer rate | Mean latency | p99 latency | Failed | Non-2xx |"
    echo "| --- | --- | --- | --- | --- | --- | --- |"
  } >>"$OUT"
  local raws=()
  for target in "${TARGETS[@]}"; do
    echo "ab ${target} for ${seconds}s..." >&2
    raw="$(ab -k -q -c "$WRK_CONNECTIONS" -t "$seconds" -n 100000000 \
      "http://127.0.0.1:${PORT}${target}" 2>&1)"
    raws+=("$raw")
    local rps rate mean p99v failed non2xx
    rps="$(awk -F': *' '/^Requests per second/ { split($2, a, " "); print a[1] }' <<<"$raw")"
    rate="$(awk -F': *' '/^Transfer rate/ { split($2, a, " "); print a[1] " KB/s" }' <<<"$raw")"
    mean="$(awk -F': *' '/^Time per request.*\(mean\)$/ { split($2, a, " "); print a[1] " ms" }' <<<"$raw")"
    p99v="$(awk '$1 == "99%" { print $2 " ms" }' <<<"$raw")"
    failed="$(awk -F': *' '/^Failed requests/ { print $2 }' <<<"$raw")"
    non2xx="$(awk -F': *' '/^Non-2xx responses/ { print $2 }' <<<"$raw")"
    echo "| \`GET ${target}\` | ${rps} | ${rate} | ${mean} | ${p99v} | ${failed:-0} | ${non2xx:-0} |" >>"$OUT"
  done
  {
    echo
    echo "<details><summary>Raw ab output</summary>"
    local i=0
    for target in "${TARGETS[@]}"; do
      echo
      echo "### \`GET ${target}\`"
      echo
      echo '```'
      echo "${raws[$i]}"
      echo '```'
      i=$((i + 1))
    done
    echo
    echo "</details>"
  } >>"$OUT"
}

if ! command -v wrk >/dev/null 2>&1; then
  LOAD_GENERATOR="wrk: not installed"
  if command -v ab >/dev/null 2>&1; then
    LOAD_GENERATOR+="; supplementary run: ApacheBench \`ab -k -c${WRK_CONNECTIONS} -t${DURATION%s}\`"
  fi
  write_header
  cat >>"$OUT" <<'EOF'
## Results

**Not run: `wrk` is not installed on the machine that generated this
file.** No numbers have been filled in, on purpose. Install wrk (e.g.
`sudo apt install wrk`, `sudo dnf install wrk` or `brew install wrk`) and
rerun `scripts/bench.sh` to replace this placeholder.

| Target | Requests/sec | Transfer/sec | Avg latency | p99 latency | Errors |
| --- | --- | --- | --- | --- | --- |
| `GET /` (index.html) | _pending_ | _pending_ | _pending_ | _pending_ | _pending_ |
| `GET /style.css` | _pending_ | _pending_ | _pending_ | _pending_ | _pending_ |
EOF
  if command -v ab >/dev/null 2>&1 && command -v curl >/dev/null 2>&1; then
    run_ab_supplement
  fi
  echo "wrk not found: wrote placeholder (and any supplementary data) to $OUT" >&2
  exit 0
fi

start_server

declare -A RAW
for target in "${TARGETS[@]}"; do
  echo "wrk ${target} for ${DURATION}..." >&2
  RAW[$target]="$(wrk -t"$WRK_THREADS" -c"$WRK_CONNECTIONS" -d"$DURATION" --latency \
    "http://127.0.0.1:${PORT}${target}")"
done

# Pulls fields out of wrk's text output.
field() { awk -v key="$2" '$1 == key { print $2; exit }' <<<"$1"; }
latency_avg() { awk '$1 == "Latency" && NF >= 4 { print $2; exit }' <<<"$1"; }
p99() { awk '$1 == "99%" { print $2; exit }' <<<"$1"; }
errors() {
  local e
  e="$(grep -E 'Socket errors|Non-2xx' <<<"$1" | tr '\n' ' ' | sed 's/ *$//')"
  echo "${e:-0}"
}

write_header
{
  echo "## Results"
  echo
  echo "| Target | Requests/sec | Transfer/sec | Avg latency | p99 latency | Errors |"
  echo "| --- | --- | --- | --- | --- | --- |"
  for target in "${TARGETS[@]}"; do
    raw="${RAW[$target]}"
    echo "| \`GET ${target}\` | $(field "$raw" "Requests/sec:") | $(field "$raw" "Transfer/sec:") | $(latency_avg "$raw") | $(p99 "$raw") | $(errors "$raw") |"
  done
  echo
  echo "## Raw wrk output"
  for target in "${TARGETS[@]}"; do
    echo
    echo "### \`GET ${target}\`"
    echo
    echo '```'
    echo "${RAW[$target]}"
    echo '```'
  done
} >>"$OUT"

echo "wrote $OUT" >&2
